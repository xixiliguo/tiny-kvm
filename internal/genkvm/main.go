package main

import (
	"bytes"
	"go/format"
	"log"
	"os"
	"text/template"
)

// Define a template.
const Body = `
func gen{{.Head}}(nums int) (data []byte, h *{{.Head}}, e []{{.Entry}}) {
	headSize := unsafe.Sizeof(*h)
	entrySize := unsafe.Sizeof(e[0])
	data = make([]byte, headSize+uintptr(nums)*entrySize)
	ptr := unsafe.Pointer(&data[0])
	h = (*{{.Head}})(ptr)
	h.{{.Num}} = {{.NumType}}(nums)
	e = unsafe.Slice((*{{.Entry}})(unsafe.Add(ptr, headSize)), nums)
	return
}
`

type Para struct {
	Head    string
	Entry   string
	Num     string
	NumType string
}

func main() {

	paras := []Para{
		{
			"KvmCpuid2",
			"KvmCpuidEntry2",
			"Nent",
			"uint32",
		},
		{
			"KvmMsrList",
			"KvmMsrEntry",
			"Nmsrs",
			"uint32",
		},
		{
			"kvm_irq_routing",
			"KvmIrqRoutingEntry",
			"Nr",
			"uint32",
		},
		{
			"KvmMsrs",
			"KvmMsrEntry",
			"Nmsrs",
			"uint32",
		},
	}

	w := bytes.NewBuffer(nil)
	w.WriteString(`// Code generated by internal/cmd/genkvm; DO NOT EDIT.

package hyper

import (
	"unsafe"
)

`)

	t := template.Must(template.New("Body").Parse(Body))
	for _, p := range paras {
		err := t.Execute(w, p)
		if err != nil {
			log.Panicf("executing template: %s", err)
		}
	}

	fmted, err := format.Source(w.Bytes())
	if err != nil {
		log.Panicf("format code: %s", err)
	}
	os.WriteFile("kvm_autogen.go", fmted, 0644)
}
